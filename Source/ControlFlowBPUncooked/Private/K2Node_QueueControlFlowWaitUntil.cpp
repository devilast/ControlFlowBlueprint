bool UK2Node_QueueControlFlowWaitUntil::Fits(const UFunction* Function, FString* OutWhyNot) const
{
	FString Why;
	const bool bFits = UControlFlowBP::IsConditionFunction(Function, Why);

	if (OutWhyNot)
	{
		*OutWhyNot = MoveTemp(Why);
	}

	return bFits;
}

UFunction* UK2Node_QueueControlFlowWaitUntil::GetPickSignature() const
{
	static const FName ConditionParam(TEXT("Condition"));

	const UFunction* WaitUntil = UControlFlowBP::StaticClass()->FindFunctionByName(GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueWaitUntil));
	const FDelegateProperty* Param = WaitUntil ? CastField<FDelegateProperty>(WaitUntil->FindPropertyByName(ConditionParam)) : nullptr;
	return Param ? Param->SignatureFunction.Get() : nullptr;
}

void UK2Node_QueueControlFlowWaitUntil::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	FName ResolvedName;
	const UFunction* Condition = ResolvePickedFunction(&ResolvedName);
	if (!CheckTargetConnected(CompilerContext) || !Condition || !Fits(Condition, nullptr))
	{
		BreakAllNodeLinks();
		return;
	}

	static const FName OwnerParam(TEXT("Owner"));
	static const FName StepNameParam(TEXT("StepName"));

	bool bSucceeded = true;
	UK2Node_CallFunction* CallNode = SpawnQueueCall(CompilerContext, SourceGraph,
		GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueWaitUntilByName), StepNameParam, bSucceeded);

	if (CallNode)
	{
		MoveToCall(CompilerContext, CallNode, PN_CheckInterval, PN_CheckInterval, bSucceeded);
		MoveToCall(CompilerContext, CallNode, PN_TimeoutSeconds, PN_TimeoutSeconds, bSucceeded);

		if (UEdGraphPin* ConditionPin = CallNode->FindPin(PN_ConditionFunction, EGPD_Input))
		{
			ConditionPin->DefaultValue = ResolvedName.ToString();
		}
		else
		{
			bSucceeded = false;
		}

		bSucceeded &= ConnectSelf(CompilerContext, SourceGraph, CallNode->FindPin(OwnerParam, EGPD_Input));

		if (!bSucceeded)
		{
			ReportExpansionFailed(CompilerContext);
		}
	}

	BreakAllNodeLinks();
}

