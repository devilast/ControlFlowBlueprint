const FName UK2Node_QueueControlFlowWaitUntil::PN_ConditionFunction(TEXT("ConditionFunction"));
const FName UK2Node_QueueControlFlowWaitUntil::PN_CheckInterval(TEXT("CheckInterval"));
const FName UK2Node_QueueControlFlowWaitUntil::PN_TimeoutSeconds(TEXT("TimeoutSeconds"));

void UK2Node_QueueControlFlowWaitUntil::CreateStepPins()
{
	CreatePickPin(LOCTEXT("ConditionPin", "Condition"),
		LOCTEXT("ConditionTooltip", "The function on this Blueprint that says when to stop waiting: it takes nothing and returns a bool."));

	UEdGraphPin* IntervalPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, PN_CheckInterval);
	IntervalPin->PinFriendlyName = LOCTEXT("CheckIntervalPin", "Check Interval");
	IntervalPin->PinToolTip = LOCTEXT("CheckIntervalTooltip", "Seconds of game time between checks of Condition. 0 checks every frame.").ToString();
	IntervalPin->DefaultValue = IntervalPin->AutogeneratedDefaultValue = TEXT("0.0");
	IntervalPin->bAdvancedView = true;

	UEdGraphPin* TimeoutPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, PN_TimeoutSeconds);
	TimeoutPin->PinFriendlyName = LOCTEXT("TimeoutPin", "Timeout Seconds");
	TimeoutPin->PinToolTip = LOCTEXT("TimeoutTooltip",
		"Fail the step if Condition is still false after this many seconds of game time - time spent paused does not count. "
		"-1 uses the flow's Default Step Timeout (set on Create Control Flow), 0 waits forever.").ToString();
	TimeoutPin->DefaultValue = TimeoutPin->AutogeneratedDefaultValue = TEXT("-1.0");
}

