{
	static bool IsStepCandidate(const UFunction* Function, const UClass* SelfClass)
	{
		return NodeUtils::IsPickableFunction(Function, SelfClass) && UEdGraphSchema_K2::FunctionCanBeUsedInDelegate(Function);
	}
}

void UK2Node_QueueControlFlowStep::AllocateDefaultPins()
{
	CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Execute);
	CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Exec, UEdGraphSchema_K2::PN_Then);

	UEdGraphPin* TargetPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UControlFlowBP::StaticClass(), PN_Target);
	TargetPin->PinToolTip = LOCTEXT("TargetTooltip", "The flow to queue this step onto.").ToString();

	UEdGraphPin* KindPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Byte, StaticEnum<EControlFlowStepKind>(), PN_StepKind);
	KindPin->PinFriendlyName = LOCTEXT("StepKindPin", "Step Kind");
	KindPin->PinToolTip = LOCTEXT("StepKindTooltip", "What kind of step this is. Filters the Function dropdown to the functions whose signature fits. Delay runs no function: it waits Seconds instead.").ToString();
	KindPin->AutogeneratedDefaultValue = KindToString(EControlFlowStepKind::Function);
	KindPin->bNotConnectable = true;

	UEdGraphPin* FunctionPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Name, PN_Function);
	FunctionPin->PinToolTip = LOCTEXT("FunctionTooltip", "The function or custom event on this Blueprint that runs the step.").ToString();
	FunctionPin->bNotConnectable = true;

	UEdGraphPin* NamePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_String, PN_StepName);
	NamePin->PinFriendlyName = LOCTEXT("StepNamePin", "Step Name");
	NamePin->PinToolTip = LOCTEXT("StepNameTooltip", "Shown in logs and Get Current Step Path. Defaults to the function's name.").ToString();
	NamePin->bAdvancedView = true;

	UEdGraphPin* PayloadPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Struct, FInstancedStruct::StaticStruct(), PN_Payload);
	PayloadPin->PinToolTip = LOCTEXT("PayloadTooltip", "Data handed back to the step: Get Payload on its handle or scope, or as the event's only parameter for a Function step.").ToString();
	PayloadPin->bAdvancedView = true;

	UEdGraphPin* FlowPin = CreatePin(EGPD_Output, UEdGraphSchema_K2::PC_Object, UControlFlowBP::StaticClass(), PN_Flow);
	FlowPin->PinToolTip = LOCTEXT("FlowTooltip", "The same flow, so steps chain.").ToString();

	CreateKindSpecificPins(StepKind);
	MirrorPropertiesToPins();
	UpdateFunctionPinsVisibility();

	if (AdvancedPinDisplay == ENodeAdvancedPins::NoPins)
	{
		AdvancedPinDisplay = ENodeAdvancedPins::Hidden;
	}

	Super::AllocateDefaultPins();
}

void UK2Node_QueueControlFlowStep::CreateKindSpecificPins(EControlFlowStepKind Kind)
{
	switch (Kind)
	{
	case EControlFlowStepKind::Wait:
		{
			UEdGraphPin* Pin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, PN_TimeoutSeconds);
			Pin->PinFriendlyName = LOCTEXT("TimeoutPin", "Timeout Seconds");
			Pin->PinToolTip = LOCTEXT("TimeoutTooltip", "Fail the step if its handle is not resolved within this many seconds of game time - time spent paused does not count. -1 uses the flow's Default Step Timeout (set on Create Control Flow), 0 waits forever.").ToString();
			Pin->DefaultValue = Pin->AutogeneratedDefaultValue = TEXT("-1.0");
			break;
		}

	case EControlFlowStepKind::Fork:
		{
			UEdGraphPin* Pin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Byte, StaticEnum<EControlFlowConcurrency>(), PN_ForkMode);
			Pin->PinFriendlyName = LOCTEXT("ForkModePin", "Mode");
			Pin->DefaultValue = Pin->AutogeneratedDefaultValue =
				StaticEnum<EControlFlowConcurrency>()->GetNameStringByValue(static_cast<int64>(EControlFlowConcurrency::Ordered));
			break;
		}

	case EControlFlowStepKind::Loop:
		{
			UEdGraphPin* ModePin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Byte, StaticEnum<EControlFlowLoopMode>(), PN_LoopMode);
			ModePin->PinFriendlyName = LOCTEXT("LoopModePin", "Mode");
			ModePin->DefaultValue = ModePin->AutogeneratedDefaultValue =
				StaticEnum<EControlFlowLoopMode>()->GetNameStringByValue(static_cast<int64>(EControlFlowLoopMode::DoWhile));

			UEdGraphPin* MaxPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Int, PN_MaxIterations);
			MaxPin->PinFriendlyName = LOCTEXT("MaxIterationsPin", "Max Iterations");
			MaxPin->PinToolTip = LOCTEXT("MaxIterationsTooltip", "0, the default, lets the loop run until its function answers Continue Looping false or the flow is cancelled. Above 0, a loop that asks for more iterations than that is stopped with an error - a backstop for a loop that is meant to end.").ToString();
			MaxPin->DefaultValue = MaxPin->AutogeneratedDefaultValue = TEXT("0");
			MaxPin->bAdvancedView = true;
			break;
		}

	case EControlFlowStepKind::Delay:
		{
			UEdGraphPin* Pin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, PN_Seconds);
			Pin->PinToolTip = LOCTEXT("SecondsTooltip", "How long the flow waits, in seconds of game time - like a Delay node, it stands still while the game is paused. 0 waits for the next frame.").ToString();
			Pin->DefaultValue = Pin->AutogeneratedDefaultValue = TEXT("1.0");
			break;
		}

	default:
		break;
	}
}

bool UK2Node_QueueControlFlowStep::IsKindSpecificPin(const UEdGraphPin* Pin)
{
	return Pin
		&& (Pin->PinName == PN_TimeoutSeconds
			|| Pin->PinName == PN_ForkMode
			|| Pin->PinName == PN_LoopMode
			|| Pin->PinName == PN_MaxIterations
			|| Pin->PinName == PN_Seconds);
}

void UK2Node_QueueControlFlowStep::SyncKindSpecificPins()
{
	TArray<UEdGraphPin*> OldPins;
	for (UEdGraphPin* Pin : Pins)
	{
		if (IsKindSpecificPin(Pin))
		{
			OldPins.Add(Pin);
		}
	}

	for (UEdGraphPin* Pin : OldPins)
	{
		Pins.Remove(Pin);
	}

	CreateKindSpecificPins(StepKind);

	RewireOldPinsToNewPins(OldPins, Pins, nullptr);

	UpdateFunctionPinsVisibility();

	if (UEdGraph* Graph = GetGraph())
	{
		Graph->NotifyGraphChanged();
	}

	if (UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this))
	{
		FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
	}
}

void UK2Node_QueueControlFlowStep::UpdateFunctionPinsVisibility()
{
	const bool bHidden = StepKind == EControlFlowStepKind::Delay;

	for (const FName PinName : { PN_Function, PN_Payload })
	{
		if (UEdGraphPin* Pin = FindPin(PinName, EGPD_Input))
		{
			if (bHidden)
			{
				Pin->BreakAllPinLinks(true);
			}

			Pin->bHidden = bHidden;
		}
	}
}

void UK2Node_QueueControlFlowStep::MirrorPropertiesToPins()
{
	if (UEdGraphPin* KindPin = FindPin(PN_StepKind))
	{
		KindPin->DefaultValue = KindToString(StepKind);
	}

	if (UEdGraphPin* FunctionPin = FindPin(PN_Function))
	{
		FunctionPin->DefaultValue = FunctionName.IsNone() ? FString() : FunctionName.ToString();
	}
}

void UK2Node_QueueControlFlowStep::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);

	if (!Pin)
	{
		return;
	}

	if (Pin->PinName == PN_StepKind)
	{
		const EControlFlowStepKind NewKind = KindFromString(Pin->DefaultValue);
		if (NewKind == StepKind)
		{
			return;
		}

		Modify();
		StepKind = NewKind;

		const UFunction* Current = ResolveStepFunction();
		FString Unused;
		if (StepKind == EControlFlowStepKind::Delay
			|| (Current && ResolveKind(UControlFlowBP::DeduceStepKind(Current, Unused), StepKind) != StepKind))
		{
			SetFunctionInternal(NAME_None);
		}

		SyncKindSpecificPins();
	}
	else if (Pin->PinName == PN_Function)
	{
		const FName NewName(*Pin->DefaultValue);
		if (NewName == FunctionName)
		{
			return;
		}

		Modify();
		SetFunctionInternal(NewName);

		FollowFunctionKind();
		SyncKindSpecificPins();
	}
}

FString UK2Node_QueueControlFlowStep::KindToString(EControlFlowStepKind Kind)
{
	return StaticEnum<EControlFlowStepKind>()->GetNameStringByValue(static_cast<int64>(Kind));
}

EControlFlowStepKind UK2Node_QueueControlFlowStep::KindFromString(const FString& Value)
{
	const int64 Parsed = StaticEnum<EControlFlowStepKind>()->GetValueByNameString(Value);
	if (Parsed == INDEX_NONE || Parsed == static_cast<int64>(EControlFlowStepKind::Invalid))
	{
		return EControlFlowStepKind::Function;
	}

	return static_cast<EControlFlowStepKind>(Parsed);
}

UFunction* UK2Node_QueueControlFlowStep::ResolveStepFunction(FName* OutResolvedName) const
{
	return UE::ControlFlowBP::NodeUtils::ResolveFunction(FBlueprintEditorUtils::FindBlueprintForNode(this), FunctionName, FunctionGuid, OutResolvedName);
}

void UK2Node_QueueControlFlowStep::SetFunctionInternal(FName NewFunctionName)
{
	FunctionName = NewFunctionName;

	const UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this);
	FunctionGuid = UE::ControlFlowBP::NodeUtils::FindFunctionGuid(Blueprint, NewFunctionName);

	if (UEdGraphPin* FunctionPin = FindPin(PN_Function))
	{
		FunctionPin->DefaultValue = NewFunctionName.IsNone() ? FString() : NewFunctionName.ToString();
	}
}

void UK2Node_QueueControlFlowStep::FollowFunctionKind()
{
	const UFunction* Function = ResolveStepFunction();
	if (!Function)
	{
		return;
	}

	FString Unused;
	const EControlFlowStepKind Actual = ResolveKind(UControlFlowBP::DeduceStepKind(Function, Unused), StepKind);
	if (Actual == EControlFlowStepKind::Invalid || Actual == StepKind)
	{
		return;
	}

	StepKind = Actual;

	if (UEdGraphPin* KindPin = FindPin(PN_StepKind))
	{
		KindPin->DefaultValue = KindToString(StepKind);
	}
}

TArray<FName> UK2Node_QueueControlFlowStep::GetCandidateFunctions() const
{
	using namespace UE::ControlFlowBP::QueueStepNode;

	TArray<FName> Names;

	const UClass* Class = UE::ControlFlowBP::NodeUtils::GetSearchClass(FBlueprintEditorUtils::FindBlueprintForNode(this));
	if (!Class)
	{
		return Names;
	}

	for (TFieldIterator<UFunction> It(Class, EFieldIteratorFlags::IncludeSuper); It; ++It)
	{
		const UFunction* Function = *It;
		if (!IsStepCandidate(Function, Class))
		{
			continue;
		}

		FString Unused;
		if (ResolveKind(UControlFlowBP::DeduceStepKind(Function, Unused), StepKind) == StepKind && IsBindable(Function, StepKind))
		{
			Names.AddUnique(Function->GetFName());
		}
	}

	Names.Sort(FNameLexicalLess());
	return Names;
}

UK2Node_QueueControlFlowStep::FQueueCall UK2Node_QueueControlFlowStep::GetQueueCall(EControlFlowStepKind Kind, bool bFunctionTakesPayload)
{
	static const FName Step(TEXT("Step"));
	static const FName Populate(TEXT("Populate"));
	static const FName Define(TEXT("Define"));
	static const FName BuildIteration(TEXT("BuildIteration"));
	static const FName StepName(TEXT("StepName"));
	static const FName TaskName(TEXT("TaskName"));

	switch (Kind)
	{
	case EControlFlowStepKind::Function:
		return bFunctionTakesPayload
			? FQueueCall{ GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueFunction), Step, StepName, true }
			: FQueueCall{ GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueSimpleFunction), Step, StepName, false };

	case EControlFlowStepKind::Wait:
		return FQueueCall{ GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueWait), Step, StepName, true };

	case EControlFlowStepKind::SubFlow:
		return FQueueCall{ GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueSubFlow), Populate, TaskName, true };

	case EControlFlowStepKind::Branch:
		return FQueueCall{ GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueBranch), Define, TaskName, true };

	case EControlFlowStepKind::Fork:
		return FQueueCall{ GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueFork), Define, TaskName, true };

	case EControlFlowStepKind::Race:
		return FQueueCall{ GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueRace), Define, TaskName, true };

	case EControlFlowStepKind::Loop:
		return FQueueCall{ GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueCombinedLoop), BuildIteration, TaskName, true };

	case EControlFlowStepKind::Delay:
		return FQueueCall{ GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueDelay), NAME_None, StepName, false };

	default:
		return FQueueCall();
	}
}

EControlFlowStepKind UK2Node_QueueControlFlowStep::ResolveKind(EControlFlowStepKind Deduced, EControlFlowStepKind Chosen)
{
	return (Deduced == EControlFlowStepKind::Fork && Chosen == EControlFlowStepKind::Race) ? EControlFlowStepKind::Race : Deduced;
}

const UFunction* UK2Node_QueueControlFlowStep::GetDelegateSignature(EControlFlowStepKind Kind, bool bFunctionTakesPayload)
{
	const FQueueCall Call = GetQueueCall(Kind, bFunctionTakesPayload);
	if (Call.Function.IsNone() || Call.DelegateParam.IsNone())
	{
		return nullptr;
	}

	const UFunction* Queue = UControlFlowBP::StaticClass()->FindFunctionByName(Call.Function);
	const FDelegateProperty* DelegateParam = Queue ? CastField<FDelegateProperty>(Queue->FindPropertyByName(Call.DelegateParam)) : nullptr;
	return DelegateParam ? DelegateParam->SignatureFunction.Get() : nullptr;
}

bool UK2Node_QueueControlFlowStep::IsBindable(const UFunction* Function, EControlFlowStepKind Kind)
{
	if (!Function)
	{
		return false;
	}

	const UFunction* Signature = GetDelegateSignature(Kind, Function->NumParms > 0);
	return Signature && Signature->IsSignatureCompatibleWith(Function);
}

