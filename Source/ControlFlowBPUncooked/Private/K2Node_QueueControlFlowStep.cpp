bool UK2Node_QueueControlFlowStep::CanCreateMatchingEvent() const
{
	const UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this);
	return Blueprint && FBlueprintEditorUtils::FindEventGraph(Blueprint) && GetDelegateSignature(StepKind, false);
}

UK2Node_CustomEvent* UK2Node_QueueControlFlowStep::CreateMatchingEvent()
{
	UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this);

	const UFunction* Signature = GetDelegateSignature(StepKind, false);
	if (!Blueprint || !Signature)
	{
		return nullptr;
	}

	const FScopedTransaction Transaction(LOCTEXT("CreateMatchingEvent", "Create Matching Step Event"));
	Modify();

	const FString KindName = StaticEnum<EControlFlowStepKind>()->GetDisplayNameTextByValue(static_cast<int64>(StepKind)).ToString().Replace(TEXT(" "), TEXT(""));
	UK2Node_CustomEvent* Event = UE::ControlFlowBP::NodeUtils::AddMatchingEvent(Blueprint, Signature, KindName + TEXT("Step"));
	if (!Event)
	{
		return nullptr;
	}

	SetFunctionInternal(Event->CustomFunctionName);
	FunctionGuid = Event->NodeGuid;

	FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
	return Event;
}

