void UK2Node_QueueControlFlowStep::ReconstructNode()
{
	FName NewName;
	if (FindRenamedFunction(NewName))
	{
		FunctionName = NewName;
	}

	FollowFunctionKind();

	Super::ReconstructNode();
}

void UK2Node_QueueControlFlowStep::PostReconstructNode()
{
	Super::PostReconstructNode();

	MirrorPropertiesToPins();
}

bool UK2Node_QueueControlFlowStep::FindRenamedFunction(FName& OutNewName) const
{
	FName ResolvedName;
	if (FunctionName.IsNone() || !ResolveStepFunction(&ResolvedName) || ResolvedName == FunctionName)
	{
		return false;
	}

	OutNewName = ResolvedName;
	return true;
}

void UK2Node_QueueControlFlowStep::HandleFunctionRenamed(UBlueprint* InBlueprint, UClass* InFunctionClass, UEdGraph* InGraph, const FName& InOldFuncName, const FName& InNewFuncName)
{
	Super::HandleFunctionRenamed(InBlueprint, InFunctionClass, InGraph, InOldFuncName, InNewFuncName);

	if (ReferencesFunction(InOldFuncName, InFunctionClass))
	{
		Modify();
		FunctionName = InNewFuncName;
		MirrorPropertiesToPins();
	}
}

void UK2Node_QueueControlFlowStep::ClearCachedBlueprintData(UBlueprint* Blueprint)
{
	Super::ClearCachedBlueprintData(Blueprint);

	FName NewName;
	if (FindRenamedFunction(NewName))
	{
		Modify();
		FunctionName = NewName;
		MirrorPropertiesToPins();
	}
}

bool UK2Node_QueueControlFlowStep::ReferencesFunction(const FName& InFunctionName, const UStruct* InScope) const
{
	using namespace UE::ControlFlowBP;

	return StepKind != EControlFlowStepKind::Delay
		&& !FunctionName.IsNone()
		&& FunctionName == InFunctionName
		&& NodeUtils::IsClassOrChildOf(NodeUtils::GetSearchClass(FBlueprintEditorUtils::FindBlueprintForNode(this)), InScope);
}

void UK2Node_QueueControlFlowStep::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
	Super::ValidateNodeDuringCompilation(MessageLog);

	if (StepKind == EControlFlowStepKind::Delay)
	{
		return;
	}

	if (FunctionName.IsNone())
	{
		MessageLog.Error(*LOCTEXT("NoFunction", "@@: pick the function this step runs.").ToString(), this);
		return;
	}

	FName ResolvedName;
	const UFunction* Function = ResolveStepFunction(&ResolvedName);
	if (!Function)
	{
		MessageLog.Error(*FText::Format(
			LOCTEXT("MissingFunction", "@@: '{0}' does not exist on this Blueprint."),
			FText::FromName(FunctionName)).ToString(), this);
		return;
	}

	FString Why;
	const EControlFlowStepKind Actual = ResolveKind(UControlFlowBP::DeduceStepKind(Function, Why), StepKind);
	if (Actual == EControlFlowStepKind::Invalid)
	{
		MessageLog.Error(*FText::Format(
			LOCTEXT("BadSignature", "@@: '{0}' cannot be a control flow step - {1}."),
			FText::FromName(ResolvedName), FText::FromString(Why)).ToString(), this);
		return;
	}

	if (!IsBindable(Function, Actual))
	{
		MessageLog.Error(*FText::Format(
			LOCTEXT("NotBindable", "@@: '{0}' has the right parameter type for a {1} step, but not the exact signature - make sure the parameter is not passed by reference."),
			FText::FromName(ResolvedName),
			StaticEnum<EControlFlowStepKind>()->GetDisplayNameTextByValue(static_cast<int64>(Actual))).ToString(), this);
		return;
	}

	if (Actual != StepKind)
	{
		const UEnum* KindEnum = StaticEnum<EControlFlowStepKind>();
		MessageLog.Warning(*FText::Format(
			LOCTEXT("KindChanged", "@@: '{0}' is now a {1} step, not a {2} step, and compiles as {1}. Refresh the node to update its pins."),
			FText::FromName(ResolvedName),
			KindEnum->GetDisplayNameTextByValue(static_cast<int64>(Actual)),
			KindEnum->GetDisplayNameTextByValue(static_cast<int64>(StepKind))).ToString(), this);
	}
}

void UK2Node_QueueControlFlowStep::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	Super::ExpandNode(CompilerContext, SourceGraph);

	UEdGraphPin* TargetPin = FindPin(PN_Target);
	if (!TargetPin || TargetPin->LinkedTo.Num() == 0)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("NoTarget", "@@ needs a Control Flow on its @@ pin.").ToString(), this, TargetPin);

		BreakAllNodeLinks();
		return;
	}

	FName ResolvedName;
	const UFunction* StepFunction = nullptr;
	EControlFlowStepKind Kind = EControlFlowStepKind::Delay;
	if (StepKind != EControlFlowStepKind::Delay)
	{
		StepFunction = ResolveStepFunction(&ResolvedName);

		FString Unused;
		Kind = StepFunction ? ResolveKind(UControlFlowBP::DeduceStepKind(StepFunction, Unused), StepKind) : EControlFlowStepKind::Invalid;
	}

	if (Kind == EControlFlowStepKind::Invalid)
	{
		BreakAllNodeLinks();
		return;
	}

	if (Kind == EControlFlowStepKind::Function && StepFunction->NumParms == 0)
	{
		UEdGraphPin* PayloadPin = FindPin(PN_Payload);
		if (PayloadPin && PayloadPin->LinkedTo.Num() > 0)
		{
			CompilerContext.MessageLog.Warning(*FText::Format(
				LOCTEXT("PayloadIgnored", "@@: '{0}' takes no parameters, so its @@ is ignored. Give the event an Instanced Struct input to receive it."),
				FText::FromName(ResolvedName)).ToString(), this, PayloadPin);
		}
	}

	const FQueueCall Call = GetQueueCall(Kind, StepFunction && StepFunction->NumParms > 0);
	UFunction* QueueFunction = UControlFlowBP::StaticClass()->FindFunctionByName(Call.Function);
	if (!QueueFunction)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("NoQueueFunction", "@@: internal error - the Control Flow queue function is missing.").ToString(), this);
		BreakAllNodeLinks();
		return;
	}

	const UEdGraphSchema_K2* Schema = CompilerContext.GetSchema();
	bool bSucceeded = true;

	UK2Node_CallFunction* CallNode = CompilerContext.SpawnIntermediateNode<UK2Node_CallFunction>(this, SourceGraph);
	CallNode->SetFromFunction(QueueFunction);
	CallNode->AllocateDefaultPins();

	const auto MoveToCall = [this, CallNode, &CompilerContext, &bSucceeded](FName FromPinName, FName ToPinName) -> void
	{
		UEdGraphPin* FromPin = FindPin(FromPinName);
		UEdGraphPin* ToPin = CallNode->FindPin(ToPinName);
		if (!FromPin || !ToPin)
		{
			bSucceeded = false;
			return;
		}

		bSucceeded &= CompilerContext.MovePinLinksToIntermediate(*FromPin, *ToPin).CanSafeConnect();
	};

	MoveToCall(UEdGraphSchema_K2::PN_Execute, UEdGraphSchema_K2::PN_Execute);
	MoveToCall(UEdGraphSchema_K2::PN_Then, UEdGraphSchema_K2::PN_Then);
	MoveToCall(PN_Target, UEdGraphSchema_K2::PN_Self);
	MoveToCall(PN_Flow, UEdGraphSchema_K2::PN_ReturnValue);
	MoveToCall(PN_StepName, Call.NameParam);

	if (Call.bTakesPayload)
	{
		MoveToCall(PN_Payload, PN_Payload);
	}

	static const FName TimeoutParam(TEXT("TimeoutSeconds"));
	static const FName ModeParam(TEXT("Mode"));
	static const FName MaxIterationsParam(TEXT("MaxIterations"));
	static const FName SecondsParam(TEXT("Seconds"));

	switch (Kind)
	{
	case EControlFlowStepKind::Wait:
		if (FindPin(PN_TimeoutSeconds))
		{
			MoveToCall(PN_TimeoutSeconds, TimeoutParam);
		}
		break;

	case EControlFlowStepKind::Fork:
		if (FindPin(PN_ForkMode))
		{
			MoveToCall(PN_ForkMode, ModeParam);
		}
		break;

	case EControlFlowStepKind::Loop:
		if (FindPin(PN_LoopMode))
		{
			MoveToCall(PN_LoopMode, ModeParam);
		}
		else if (UEdGraphPin* CallModePin = CallNode->FindPin(ModeParam))
		{
			CallModePin->DefaultValue = StaticEnum<EControlFlowLoopMode>()->GetNameStringByValue(static_cast<int64>(EControlFlowLoopMode::DoWhile));
		}

		if (FindPin(PN_MaxIterations))
		{
			MoveToCall(PN_MaxIterations, MaxIterationsParam);
		}
		break;

	case EControlFlowStepKind::Delay:
		MoveToCall(PN_Seconds, SecondsParam);
		break;

	default:
		break;
	}

	if (!Call.DelegateParam.IsNone())
	{
		UK2Node_Self* SelfNode = CompilerContext.SpawnIntermediateNode<UK2Node_Self>(this, SourceGraph);
		SelfNode->AllocateDefaultPins();

		UK2Node_CreateDelegate* CreateDelegateNode = CompilerContext.SpawnIntermediateNode<UK2Node_CreateDelegate>(this, SourceGraph);
		CreateDelegateNode->AllocateDefaultPins();

		UEdGraphPin* DelegateParamPin = CallNode->FindPin(Call.DelegateParam);
		bSucceeded &= DelegateParamPin && Schema->TryCreateConnection(CreateDelegateNode->GetDelegateOutPin(), DelegateParamPin);
		bSucceeded &= Schema->TryCreateConnection(SelfNode->FindPinChecked(UEdGraphSchema_K2::PN_Self), CreateDelegateNode->GetObjectInPin());

		CreateDelegateNode->SetFunction(ResolvedName);
	}

	if (!bSucceeded)
	{
		CompilerContext.MessageLog.Error(*LOCTEXT("ExpansionFailed", "@@: internal error while expanding the step.").ToString(), this);
	}

	BreakAllNodeLinks();
}

FText UK2Node_QueueControlFlowStep::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	if (TitleType == ENodeTitleType::MenuTitle)
	{
		return LOCTEXT("MenuTitle", "Queue Step");
	}

	const FText KindText = StaticEnum<EControlFlowStepKind>()->GetDisplayNameTextByValue(static_cast<int64>(StepKind));
	if (FunctionName.IsNone() || StepKind == EControlFlowStepKind::Delay)
	{
		return FText::Format(LOCTEXT("TitleNoFunction", "Queue Step\n{0}"), KindText);
	}

	return FText::Format(LOCTEXT("Title", "Queue Step\n{0}: {1}"), KindText, FText::FromName(FunctionName));
}

