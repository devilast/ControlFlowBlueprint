FText UK2Node_QueueControlFlowWaitForDispatcher::GetCreateFunctionLabel(const UEdGraphPin& Pin) const
{
	if (!IsFunctionPin(Pin) || !IsObjectSelf() || !FBlueprintEditorUtils::FindBlueprintForNode(this))
	{
		return FText::GetEmpty();
	}

	return LOCTEXT("CreateDispatcher", "[Create a new event dispatcher]");
}

UObject* UK2Node_QueueControlFlowWaitForDispatcher::CreateFunctionFor(const UEdGraphPin& Pin)
{
	using namespace UE::ControlFlowBP;

	UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this);
	if (!Blueprint || GetCreateFunctionLabel(Pin).IsEmpty())
	{
		return nullptr;
	}

	const FScopedTransaction Transaction(LOCTEXT("CreateDispatcherTransaction", "Create Event Dispatcher"));
	Modify();

	const FName Name = NodeUtils::AddEventDispatcher(Blueprint, TEXT("NewEventDispatcher"));
	if (Name.IsNone())
	{
		return nullptr;
	}

	SetPick(Name);

	return NodeUtils::FindDispatcherGraph(GetObjectClass(), Name);
}

