bool UK2Node_QueueControlFlowWaitForDispatcher::IsObjectSelf() const
{
	const UEdGraphPin* ObjectPin = FindPin(UEdGraphSchema_K2::PN_Self, EGPD_Input);
	return !ObjectPin || ObjectPin->LinkedTo.Num() == 0 || ObjectPin->LinkedTo[0]->PinType.PinSubCategory == UEdGraphSchema_K2::PSC_Self;
}

const UClass* UK2Node_QueueControlFlowWaitForDispatcher::GetObjectClass() const
{
	using namespace UE::ControlFlowBP;

	if (IsObjectSelf())
	{
		return NodeUtils::GetSearchClass(FBlueprintEditorUtils::FindBlueprintForNode(this));
	}

	const UEdGraphPin* ObjectPin = FindPin(UEdGraphSchema_K2::PN_Self, EGPD_Input);
	const UClass* Class = Cast<UClass>(ObjectPin->LinkedTo[0]->PinType.PinSubCategoryObject.Get());

	const UBlueprint* ClassBlueprint = UBlueprint::GetBlueprintFromClass(Class);
	return ClassBlueprint ? NodeUtils::GetSearchClass(ClassBlueprint) : Class;
}

FName UK2Node_QueueControlFlowWaitForDispatcher::ResolvePickedName() const
{
	using namespace UE::ControlFlowBP;

	const UClass* Class = GetObjectClass();
	if (!Class || Picked.Name.IsNone() || NodeUtils::GetEventDispatchers(Class).Contains(Picked.Name))
	{
		return Picked.Name;
	}

	const FName Renamed = NodeUtils::FindDispatcherNameByGuid(Class, Picked.Guid);
	return Renamed.IsNone() ? Picked.Name : Renamed;
}

FGuid UK2Node_QueueControlFlowWaitForDispatcher::FindPickGuid(FName Name) const
{
	return UE::ControlFlowBP::NodeUtils::FindDispatcherGuid(GetObjectClass(), Name);
}

void UK2Node_QueueControlFlowWaitForDispatcher::HandleVariableRenamed(UBlueprint* InBlueprint, UClass* InVariableClass, UEdGraph* InGraph, const FName& InOldVarName, const FName& InNewVarName)
{
	Super::HandleVariableRenamed(InBlueprint, InVariableClass, InGraph, InOldVarName, InNewVarName);

	if (ReferencesVariable(InOldVarName, InVariableClass))
	{
		Modify();
		Picked.Name = InNewVarName;
		MirrorPropertiesToPins();
	}
}

bool UK2Node_QueueControlFlowWaitForDispatcher::ReferencesVariable(const FName& InVarName, const UStruct* InScope) const
{
	return !Picked.Name.IsNone() && Picked.Name == InVarName && UE::ControlFlowBP::NodeUtils::IsClassOrChildOf(GetObjectClass(), InScope);
}

void UK2Node_QueueControlFlowWaitForDispatcher::ExpandNode(FKismetCompilerContext& CompilerContext, UEdGraph* SourceGraph)
{
	using namespace UE::ControlFlowBP;

	Super::ExpandNode(CompilerContext, SourceGraph);

	if (!CheckTargetConnected(CompilerContext) || Picked.Name.IsNone())
	{
		BreakAllNodeLinks();
		return;
	}

	const UClass* ObjectClass = GetObjectClass();
	const FName DispatcherName = ResolvePickedName();
	if (ObjectClass && !NodeUtils::GetEventDispatchers(ObjectClass).Contains(DispatcherName))
	{
		CompilerContext.MessageLog.Error(*FText::Format(
			LOCTEXT("NoSuchDispatcher", "@@: {0} has no event dispatcher named '{1}'. Pick one of its own, or cast Object to the type that has it."),
			FBlueprintEditorUtils::GetFriendlyClassDisplayName(ObjectClass), FText::FromName(DispatcherName)).ToString(), this);
		BreakAllNodeLinks();
		return;
	}

	static const FName ObjectParam(TEXT("Target"));
	static const FName StepNameParam(TEXT("StepName"));

	bool bSucceeded = true;
	UK2Node_CallFunction* CallNode = SpawnQueueCall(CompilerContext, SourceGraph,
		GET_FUNCTION_NAME_CHECKED(UControlFlowBP, QueueWaitForEventDispatcher), StepNameParam, bSucceeded);

	if (CallNode)
	{
		MoveToCall(CompilerContext, CallNode, PN_TimeoutSeconds, PN_TimeoutSeconds, bSucceeded);

		if (UEdGraphPin* NamePin = CallNode->FindPin(PN_DispatcherName, EGPD_Input))
		{
			NamePin->DefaultValue = DispatcherName.ToString();
		}
		else
		{
			bSucceeded = false;
		}

		const UEdGraphPin* ObjectPin = FindPin(UEdGraphSchema_K2::PN_Self, EGPD_Input);
		if (ObjectPin && ObjectPin->LinkedTo.Num() > 0)
		{
			MoveToCall(CompilerContext, CallNode, UEdGraphSchema_K2::PN_Self, ObjectParam, bSucceeded);
		}
		else
		{
			bSucceeded &= ConnectSelf(CompilerContext, SourceGraph, CallNode->FindPin(ObjectParam, EGPD_Input));
		}

		if (!bSucceeded)
		{
			ReportExpansionFailed(CompilerContext);
		}
	}

	BreakAllNodeLinks();
}

