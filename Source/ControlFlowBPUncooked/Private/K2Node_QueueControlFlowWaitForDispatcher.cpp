const FName UK2Node_QueueControlFlowWaitForDispatcher::PN_DispatcherName(TEXT("DispatcherName"));
const FName UK2Node_QueueControlFlowWaitForDispatcher::PN_TimeoutSeconds(TEXT("TimeoutSeconds"));

void UK2Node_QueueControlFlowWaitForDispatcher::CreateStepPins()
{
	UEdGraphPin* ObjectPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Object, UObject::StaticClass(), UEdGraphSchema_K2::PN_Self);
	ObjectPin->PinFriendlyName = LOCTEXT("ObjectPin", "Object");
	ObjectPin->PinToolTip = LOCTEXT("ObjectTooltip", "The object whose event dispatcher to wait for. Unconnected, this Blueprint itself.").ToString();

	CreatePickPin(LOCTEXT("DispatcherPin", "Event Dispatcher"),
		LOCTEXT("DispatcherTooltip", "One of Object's event dispatchers, Blueprint or C++. The step finishes the next time it is called."));

	UEdGraphPin* TimeoutPin = CreatePin(EGPD_Input, UEdGraphSchema_K2::PC_Real, UEdGraphSchema_K2::PC_Float, PN_TimeoutSeconds);
	TimeoutPin->PinFriendlyName = LOCTEXT("TimeoutPin", "Timeout Seconds");
	TimeoutPin->PinToolTip = LOCTEXT("TimeoutTooltip",
		"Fail the step if the dispatcher has not been called after this many seconds of game time - time spent paused does not count. "
		"-1 uses the flow's Default Step Timeout (set on Create Control Flow), 0 waits forever.").ToString();
	TimeoutPin->DefaultValue = TimeoutPin->AutogeneratedDefaultValue = TEXT("-1.0");
}

